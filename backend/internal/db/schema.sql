-- Skema lengkap Boo Dou untuk dipasang manual di server (PostgreSQL 13 ke atas).
-- Setara dengan migrations/00001_init.sql dan 00002_attachment_position.sql.
--
-- Jalankan sekali di database kosong, sebagai user pemilik database:
--   psql "postgres://USER:PASSWORD@HOST:5432/NAMA_DB" -f schema.sql
--
-- File ini juga membuat tabel goose_db_version dan menandai migrasi 1 dan 2
-- sudah jalan. Tanpa itu, backend akan mencoba membuat ulang tabel saat start
-- dan gagal. Kalau nanti ada migrasi baru (00003 dan seterusnya), backend
-- menjalankannya sendiri saat start; file ini tidak perlu diubah.
--
-- Semua dalam satu transaksi: kalau satu perintah gagal, tidak ada yang tersimpan.

BEGIN;

CREATE TABLE conversations (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    title      text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX conversations_updated_at_idx ON conversations (updated_at DESC);

CREATE TABLE messages (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    conversation_id uuid NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    role            text NOT NULL CHECK (role IN ('user', 'assistant')),
    content         text NOT NULL DEFAULT '',
    status          text NOT NULL DEFAULT 'complete' CHECK (status IN ('complete', 'stopped', 'error')),
    model           text NOT NULL DEFAULT '',
    -- clock_timestamp, not now(): two inserts in one transaction must still sort apart.
    created_at      timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX messages_conversation_created_idx ON messages (conversation_id, created_at);

CREATE TABLE attachments (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    -- NULL until the message that uses it is sent; orphans are cleaned up later.
    message_id  uuid REFERENCES messages (id) ON DELETE CASCADE,
    mime        text NOT NULL CHECK (mime IN ('image/jpeg', 'image/png', 'image/webp')),
    size_bytes  integer NOT NULL CHECK (size_bytes > 0),
    width       integer NOT NULL CHECK (width > 0),
    height      integer NOT NULL CHECK (height > 0),
    sha256      text NOT NULL,
    storage_key text NOT NULL UNIQUE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    -- Order within a message as the user attached it.
    position    integer
);

CREATE INDEX attachments_message_idx ON attachments (message_id);
CREATE INDEX attachments_orphan_idx ON attachments (created_at) WHERE message_id IS NULL;

-- Same table goose creates, so the backend sees migrations 1 and 2 as done.
CREATE TABLE goose_db_version (
    id         integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    version_id bigint NOT NULL,
    is_applied boolean NOT NULL,
    tstamp     timestamp NOT NULL DEFAULT now()
);

INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true), (1, true), (2, true);

COMMIT;
